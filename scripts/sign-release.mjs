import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import {spawnSync} from 'node:child_process';
const [folder,keyFile]=process.argv.slice(2);
if(!folder||!keyFile)throw new Error('用法：node scripts/sign-release.mjs 产物目录 私钥路径；不会生成密钥');
const source=fs.readFileSync(new URL('../mdpreview_core/release_sig.py',import.meta.url),'utf8');
const pinned=/^RELEASE_PUBKEY_B64 = '([^']*)'/m.exec(source)?.[1];
if(!pinned)throw new Error('生产公钥未配置，发布已禁用');
const key=crypto.createPrivateKey(fs.readFileSync(keyFile));
if(key.asymmetricKeyType!=='ec'||key.asymmetricKeyDetails?.namedCurve!=='prime256v1')throw new Error('必须使用P-256密钥');
const pub=crypto.createPublicKey(key).export({format:'der',type:'spki'}).subarray(-65);
if(!pub.equals(Buffer.from(pinned,'base64')))throw new Error('私钥不匹配固定生产公钥');
const files=fs.readdirSync(folder).filter(n=>/^mdPreview-\d+\.\d+\.\d+(?:\.\d+)?-(arm64|x86_64|universal)\.(zip|dmg)$/.test(n)).sort();
if(!files.length)throw new Error('无可签名架构标记产物');
if(files.some(n=>n.includes('-universal.')))throw new Error('universal产物需独立架构验收流程，当前签名入口拒绝未经证明的通用命名');
const manifest=Buffer.from(files.map(n=>crypto.createHash('sha256').update(fs.readFileSync(path.join(folder,n))).digest('hex')+'  '+n).join('\n')+'\n');
const signature=crypto.sign('sha256',manifest,key);
fs.writeFileSync(path.join(folder,'SHA256SUMS'),manifest,{flag:'wx'});
fs.writeFileSync(path.join(folder,'SHA256SUMS.sig'),signature,{flag:'wx'});
console.log('已签名现有产物；未上传或发布');
