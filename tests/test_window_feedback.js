const assert = require('node:assert/strict');
const fs = require('node:fs');
const { JSDOM } = require('jsdom');

(async () => {
  const dom = new JSDOM('<div id="updateBubble"><div class="update-bubble-body"><span class="update-bubble-text"></span></div></div><div id="page"><div id="content">Long document</div></div><div class="scroll-wrap"></div>', { runScripts: 'outside-only', pretendToBeVisual: true });
  const w = dom.window;
  w.eval(fs.readFileSync('frontend/updates.js', 'utf8'));
  w.eval(fs.readFileSync('frontend/reading-progress.js', 'utf8'));
  const bubble = w.document.getElementById('updateBubble');
  const cached = { phase: 'idle', automatic: false, detail: 'up to date' };
  let snapshot = cached;
  const calls = [];
  const feedback = w.UpdateFeedback.create({ document: w.document, t: en => en, Bridge: { ready: () => true, call: async (name, ...args) => { calls.push([name, ...args]); return name === 'get_update_state' ? snapshot : {success:true}; } } });
  const visible = () => bubble.classList.contains('visible');
  feedback.updateFeedbackState(cached);
  assert.equal(visible(), false, 'a historical broadcast before the first refresh stays hidden');
  await feedback.refreshUpdateState();
  assert.equal(visible(), false, 'a historical snapshot stays hidden');
  feedback.updateFeedbackState({ phase: 'checking', automatic: false });
  feedback.updateFeedbackState(cached);
  assert.equal(visible(), false, 'another window’s manual check does not show the result here');
  feedback.showManualUpdateCheckResult();
  assert.equal(visible(), true, 'the requesting window can show an explicit fresh result');
  await feedback.refreshUpdateState();
  assert.equal(visible(), true, 'refocusing the requesting window preserves its visible result');
  feedback.dismissUpdateBubble();
  await feedback.refreshUpdateState();
  assert.equal(visible(), false, 'refocusing does not revive a dismissed result');
  snapshot = { ...cached, automatic: true };
  await feedback.refreshUpdateState();
  assert.equal(visible(), false, 'background checks stay silent');
  feedback.updateFeedbackState({ phase: 'retrying', automatic: false, code: 'quit-gap-settlement-pending', error: null });
  assert.equal(visible(), false, 'waiting for the install helper is not an error notification');
  feedback.updateFeedbackState({ phase: 'retrying', automatic: false, code: 'network-timeout', error: 'network' });
  assert.equal(visible(), true, 'a real manual-check network failure remains visible');
  const retry = bubble.querySelector('.update-retry'), help = bubble.querySelector('.update-help');
  assert.equal(retry.hidden, false);
  assert.equal(help.textContent, 'Download manually');
  help.click();
  await new Promise(resolve => setTimeout(resolve, 0));
  assert.deepEqual(calls.at(-1), ['open_external_link', 'https://github.com/tahoeliu/mdPreview/releases/latest']);
  let approveCount = 0;
  feedback.updateFeedbackState({ phase:'failed', automatic:false, code:'network-timeout', error:'network' });
  const originalCall = calls.length;
  snapshot = { phase:'retrying', automatic:false, code:'network-timeout', error:'network' };
  retry.click();
  await new Promise(resolve => setTimeout(resolve, 0));
  assert.equal(calls[originalCall][0], 'retry_update');
  // A retry may return a stale retrying snapshot before the download starts.
  snapshot = { phase:'retrying', automatic:false, code:'network-timeout', error:'network' };
  await feedback.refreshUpdateState();
  feedback.updateFeedbackState({ phase:'downloading', automatic:false, version:'2.1.0', progress:0 });
  feedback.updateFeedbackState({ phase:'ready', automatic:false, version:'2.1.0' });
  await new Promise(resolve => setTimeout(resolve, 0));
  approveCount = calls.filter(call => call[0] === 'approve_update').length;
  assert.equal(approveCount, 1, 'retrying and validating an update requests installation once');
  feedback.updateFeedbackState({ phase:'failed', automatic:false, code:'quit-gap-inconclusive', error:'unknown' });
  assert.equal(retry.hidden, true);
  assert.equal(help.textContent, 'Report an Issue');
  help.click();
  await new Promise(resolve => setTimeout(resolve, 0));
  assert.equal(calls.at(-1)[0], 'report_issue');
  // Drive the actual five-second timer without waiting in real time.
  let scheduled;
  const realSetTimeout = w.setTimeout, realClearTimeout = w.clearTimeout;
  w.setTimeout = (fn, ms) => { assert.equal(ms, 5000); scheduled = fn; return 1; };
  w.clearTimeout = () => { scheduled = null; };
  const downloading = { phase: 'downloading', automatic: false, version: '2.2.0', progress: 9 };
  feedback.updateFeedbackState(downloading);
  assert.equal(visible(), true, 'manual download initially shows progress');
  feedback.updateFeedbackState({ ...downloading, progress: 55 });
  scheduled();
  assert.equal(visible(), false, 'progress updates do not reset the auto-hide timer');
  feedback.showActiveUpdate({ ...downloading, progress: 55 });
  assert.equal(visible(), true, 'menu reopens an active download');
  feedback.dismissUpdateBubble();
  feedback.showActiveUpdate({ ...downloading, progress: 70 });
  assert.equal(visible(), true, 'menu reopens after the close button');
  scheduled();
  feedback.updateFeedbackState({ phase: 'ready', automatic: false, version: '2.2.0' });
  assert.equal(visible(), true, 'download completion is shown after auto-hide');
  feedback.updateFeedbackState({ ...downloading, automatic: true, version: '2.3.0' });
  feedback.showActiveUpdate({ ...downloading, automatic: true, version: '2.3.0' });
  scheduled();
  feedback.updateFeedbackState({ phase: 'failed', automatic: true, version: '2.3.0', error: 'network' });
  assert.equal(visible(), true, 'failure is shown after the user opens a background download');
  w.setTimeout = realSetTimeout; w.clearTimeout = realClearTimeout;
  const scroller = w.document.querySelector('.scroll-wrap');
  Object.defineProperties(scroller, { scrollHeight: { value: 4000 }, clientHeight: { value: 500 } });
  scroller.scrollTop = 500;
  scroller.dispatchEvent(new w.Event('scroll'));
  w.dispatchEvent(new w.Event('resize'));
  await new Promise(resolve => w.requestAnimationFrame(resolve));
  assert.equal(w.document.querySelector('.read-hud'), null, 'reading HUD is absent');
  assert.equal(w.document.querySelector('.read-progress > div').style.transform, 'scaleX(0.1429)');
  dom.window.close();
  console.log('window feedback: ok');
})().catch(error => { console.error(error); process.exitCode = 1; });
